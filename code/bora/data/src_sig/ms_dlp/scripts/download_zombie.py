# Make the freshly-cloned Zombie tree build standalone in this environment.
# Every patch is idempotent and recorded in the log; the upstream clone is
# otherwise untouched. These were derived empirically while building the
# regexp -> ZoKrates -> CirC (R1CS) pipeline for the BORA experiments.
def apply_patches():
    applied = []

    # P1: provide the `../curve-constraint-tests` path-dependency that the
    # vendored circ/third_party/curve25519 expects; the actual crate lives in
    # the curves submodule, so we symlink it (relative link, stays portable).
    tp = os.path.join(DEST, "circ", "third_party")
    link = os.path.join(tp, "curve-constraint-tests")
    rel_target = os.path.join("curves", "curve-constraint-tests")
    if not os.path.isdir(tp):
        applied.append("P1 WARN: circ/third_party not found")
    elif os.path.lexists(link):
        applied.append("P1 curve-constraint-tests: already present (skip)")
    elif os.path.isdir(os.path.join(tp, rel_target)):
        os.symlink(rel_target, link)
        applied.append("P1 circ/third_party/curve-constraint-tests -> %s (symlink)"
                       % rel_target)
    else:
        applied.append("P1 WARN: %s missing; cannot link curve-constraint-tests"
                       % rel_target)

    # P2: drop the dangling `pub mod tmp;` in circ/src/witnesses/mod.rs. The
    # tmp.rs file matches circ's own .gitignore ("tmp*") so it was never
    # committed; a clean clone can't resolve the module. It is unused
    # everywhere, so we comment the declaration out.
    wmod = os.path.join(DEST, "circ", "src", "witnesses", "mod.rs")
    if os.path.isfile(wmod):
        with open(wmod) as f:
            txt = f.read()
        if "pub mod tmp;" in txt:
            txt = txt.replace(
                "pub mod tmp;",
                "// pub mod tmp;  // download_zombie.py: gitignored, "
                "uncommitted, unused")
            with open(wmod, "w") as f:
                f.write(txt)
            applied.append("P2 circ/src/witnesses/mod.rs: commented dangling "
                           "`pub mod tmp;`")
        else:
            applied.append("P2 witnesses/mod.rs: no `pub mod tmp;` (skip)")
    else:
        applied.append("P2 WARN: circ/src/witnesses/mod.rs not found")

    # P3: the package is `circ` but the fork overrode [lib] to name
    # "circ_zkmb"; every example (circ.rs, run_zok.rs) does `use circ::`, so
    # they cannot resolve the lib. Internal code uses `crate::`, so renaming the
    # lib target back to "circ" fixes the examples without affecting anything
    # else. (The cdylib is only consumed by the middlebox/TLS side we don't use.)
    cargo = os.path.join(DEST, "circ", "Cargo.toml")
    if os.path.isfile(cargo):
        with open(cargo) as f:
            txt = f.read()
        if 'name = "circ_zkmb"' in txt:
            txt = txt.replace('name = "circ_zkmb"', 'name = "circ"')
            with open(cargo, "w") as f:
                f.write(txt)
            applied.append('P3 circ/Cargo.toml: [lib] name "circ_zkmb" -> "circ"')
        else:
            applied.append("P3 circ/Cargo.toml: lib already named circ (skip)")
    else:
        applied.append("P3 WARN: circ/Cargo.toml not found")

    # P4: fix the stale Spartan NIZK::prove / verify call sites in
    # circ/examples/run_zok.rs. Upstream still calls an older batched API
    #   NIZK::prove(&inst, &vec![vars], &vec![input], &gens, &mut tr)
    # but the vendored Spartan submodule's NIZK (third_party/Spartan, src/lib.rs)
    # takes the vars assignment BY VALUE and the input BY REFERENCE:
    #   NIZK::prove(&inst, vars, &input, &gens, &mut tr)
    #   proof.verify(&inst, &input, &mut tr, &gens)
    # Without this the run_zok example does not compile (the `circ` example,
    # which verify_build compiles, is unaffected and already builds). We rewrite
    # only ACTIVE lines -- any line whose first non-space char is `//` is a
    # comment and is left untouched, since run_zok.rs keeps several commented
    # variants (including an already-correct one) we must not disturb.
    rzok = os.path.join(DEST, "circ", "examples", "run_zok.rs")
    spartan_subs = [
        ("&vec![var_assignment]", "var_assignment"),                # vars by value
        ("&vec![input_assignment.clone()]", "&input_assignment"),   # input by ref
        ("&vars_list", "var_assignment.clone()"),                   # batch -> single
        ("&inputs_list", "&input_assignment"),                      # batch -> single
    ]
    if os.path.isfile(rzok):
        with open(rzok) as f:
            src_lines = f.readlines()
        out_lines, nfixed = [], 0
        for ln in src_lines:
            if ln.lstrip().startswith("//"):       # never touch comments
                out_lines.append(ln)
                continue
            new = ln
            for old, rep in spartan_subs:
                new = new.replace(old, rep)
            if new != ln:
                nfixed += 1
            out_lines.append(new)
        if nfixed:
            with open(rzok, "w") as f:
                f.writelines(out_lines)
            applied.append("P4 circ/examples/run_zok.rs: rewrote %d line(s) to the "
                           "single-assignment Spartan NIZK prove/verify API" % nfixed)
        else:
            applied.append("P4 run_zok.rs: Spartan NIZK calls already current (skip)")
    else:
        applied.append("P4 WARN: circ/examples/run_zok.rs not found")

    # NOTE (no file patch): circ/ must NOT be built in place if it sits inside
    # an enclosing Cargo workspace -- adding a local [workspace] re-resolves the
    # lockfile and pulls MSRV-incompatible crates (syn/quote needing rustc 1.71
    # vs the pinned 1.69 nightly). The verified recipe builds a COPY of circ/
    # outside any workspace with the committed Cargo.lock and `--locked`
    # (see build_circ / verify_build).
    applied.append("note: build circ OUT of any parent Cargo workspace "
                   "(--locked, committed lock); see verify_build")

    return applied


# run a command in a given directory with optional extra env; never raises.
def run_in(cmd, cwd, timeout=None, extra_env=None):
    env = dict(os.environ)
    if extra_env:
        env.update(extra_env)
    try:
        p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True,
                           timeout=timeout, env=env)
        return p.returncode, p.stdout, p.stderr
    except FileNotFoundError as e:
        return -1, "", str(e)
    except subprocess.TimeoutExpired:
        return -2, "", "timed out after %ds" % timeout


# Verify the cloned Zombie actually COMPILES (regexp pipeline). Returns a list
# of (component, ok, detail). This is the verified build recipe derived for the
# BORA experiments:
#   - regex/TestRegex: plain `make` in place (no workspace issue).
#   - circ (zokrates -> R1CS): build a COPY of circ/ in a temp dir OUTSIDE any
#     enclosing Cargo workspace, with the committed Cargo.lock and `--locked`
#     (so the MSRV-incompatible re-resolution never happens) and system
#     GMP/MPFR/MPC via CARGO_FEATURE_USE_SYSTEM_LIBS=1 (so gmp-mpfr-sys links
#     the system libs instead of building+`make check`-ing a bundled MPFR,
#     which fails its tsprintf test on modern glibc).
# The temp build dir is removed afterwards; this confirms compilation, it does
# not leave an in-tree circ binary (the parent workspace prevents that).
def verify_build():
    results = []
    abs_dest = os.path.abspath(DEST)

    # 1. regex/TestRegex via make (in place).
    regex_dir = os.path.join(abs_dest, "regex")
    if os.path.isdir(regex_dir):
        rc, _o, err = run_in(["make"], regex_dir, BUILD_TIMEOUT)
        ok = rc == 0 and os.path.isfile(os.path.join(regex_dir, "bin", "TestRegex"))
        results.append(("regex/TestRegex (make)", ok,
                        "built bin/TestRegex" if ok
                        else "FAILED: %s" % (err.strip()[-200:] or "rc=%d" % rc)))
    else:
        results.append(("regex/TestRegex (make)", False, "regex/ not found"))

    # 2. circ example via cargo, in a temp copy outside any workspace.
    circ_src = os.path.join(abs_dest, "circ")
    if not os.path.isdir(circ_src):
        results.append(("circ (cargo)", False, "circ/ not found"))
        return results
    tmp = tempfile.mkdtemp(prefix="zombie_circ_build_")
    try:
        circ_build = os.path.join(tmp, "circ")

        # Ignore ONLY the top-level cargo build dir and .git -- anchored to the
        # circ root, so we do NOT also drop the source module circ/src/target/
        # (an unanchored "target" pattern would, breaking the build).
        def _root_ignore(dirpath, names):
            if os.path.abspath(dirpath) == os.path.abspath(circ_src):
                return {n for n in names if n in ("target", ".git")}
            return set()

        shutil.copytree(circ_src, circ_build, symlinks=True, ignore=_root_ignore)
        rc, _o, err = run_in(
            ["cargo", "build", "--release", "--example", "circ", "--locked"],
            circ_build, BUILD_TIMEOUT,
            extra_env={"CARGO_FEATURE_USE_SYSTEM_LIBS": "1"})
        circ_bin = os.path.join(circ_build, "target", "release", "examples", "circ")
        ok = rc == 0 and os.path.isfile(circ_bin)
        results.append(("circ (cargo, out-of-workspace --locked, system-libs)", ok,
                        "compiled circ example" if ok
                        else "FAILED: %s" % (err.strip()[-300:] or "rc=%d" % rc)))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return results


def write_upstream(commit):
    lines = [
        "repo:      %s" % ZOMBIE_URL,
        "commit:    %s" % commit,
        "retrieved: %s" % gen_run_date(),
        "license:   %s" % LICENSE_NOTE,
    ]
    with open(os.path.join(DEST, "UPSTREAM.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")


