# total file count and byte size of a directory tree (stdlib; no `du`).
def tree_size(root):
    nfiles, nbytes = 0, 0
    for dirpath, _dirs, names in os.walk(root):
        for name in names:
            try:
                nbytes += os.path.getsize(os.path.join(dirpath, name))
                nfiles += 1
            except OSError:
                pass
    return nfiles, nbytes


# run a command, returning (rc, stdout, stderr); rc=-1 if git is absent,
# rc=-2 on timeout. Never raises.
def run(cmd, timeout=None):
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        return p.returncode, p.stdout.strip(), p.stderr.strip()
    except FileNotFoundError:
        return -1, "", "`git` not found on PATH"
    except subprocess.TimeoutExpired:
        return -2, "", "clone timed out after %ds" % timeout


# probe for a C/C++ header via a no-output g++ syntax check (no temp file).
def have_header(header):
    if shutil.which("g++") is None:
        return False, "g++ absent"
    src = "#include <%s>\nint main(){ return 0; }\n" % header
    try:
        p = subprocess.run(["g++", "-x", "c++", "-fsyntax-only", "-"],
                           input=src, capture_output=True, text=True, timeout=30)
        return (p.returncode == 0,
                "ok" if p.returncode == 0 else "%s not found" % header)
    except (OSError, subprocess.TimeoutExpired) as e:
        return False, str(e)


# is the pinned rust nightly installed (via rustup)?
def have_rust_nightly():
    if shutil.which("rustup") is None:
        return False, "rustup absent"
    rc, out, _err = run(["rustup", "toolchain", "list"])
    if rc != 0:
        return False, "rustup query failed"
    return (RUST_NIGHTLY in out,
            "installed" if RUST_NIGHTLY in out else "toolchain missing")


# test one dependency; returns (ok, detail).
def check_one(kind, probe):
    if kind == "bin":
        path = shutil.which(probe)
        return (path is not None, path or "not on PATH")
    if kind == "py":
        rc, _o, _e = run(["python3", "-c", "import %s" % probe])
        return (rc == 0, "import ok" if rc == 0 else "import failed")
    if kind == "hdr":
        return have_header(probe)
    if kind == "rustn":
        return have_rust_nightly()
    return False, "unknown probe"


# run the whole dependency table; returns list of dicts.
def check_dependencies():
    results = []
    for label, kind, probe, hint, need in DEPS:
        ok, detail = check_one(kind, probe)
        results.append({"label": label, "ok": ok, "detail": detail,
                        "hint": hint, "need": need})
    return results


# build a consolidated, copy-pasteable list of commands that installs every
# MISSING dependency: all `apt install` hints are merged into one line; other
# hints (rustup, pip, ...) are emitted as their own deduplicated lines.
def install_commands(deps):
    apt_pkgs, other = [], []
    for d in deps:
        if d["ok"]:
            continue
        hint = d["hint"]
        if hint.startswith("apt install "):
            for pkg in hint[len("apt install "):].split():
                if pkg not in apt_pkgs:
                    apt_pkgs.append(pkg)
        elif hint not in other:
            other.append(hint)
    cmds = []
    if apt_pkgs:
        cmds.append("sudo apt install -y " + " ".join(apt_pkgs))
    cmds.extend(other)
    return cmds


def write_log(status, commit, nfiles, nbytes, error, deps, patches=None,
              builds=None):
    lines = [gen_report_header("zombie source retrieval"), ""]
    lines.append("repo:    %s" % ZOMBIE_URL)
    lines.append("dest:    %s/   (full clone, .git retained)" % DEST)
    lines.append("status:  %s" % status)
    lines.append("commit:  %s" % (commit or "n/a"))
    lines.append("license: %s" % LICENSE_NOTE)
    if status == "OK":
        lines.append("size:    %d files, %.1f MiB"
                     % (nfiles, nbytes / (1024.0 * 1024.0)))
    if error:
        lines.append("error:   %s" % error)

    if patches:
        lines.append("")
        lines.append("[patches]  (applied to make the clone build standalone)")
        for p in patches:
            lines.append("  %s" % p)

    if builds:
        n_ok = sum(1 for (_c, ok, _d) in builds if ok)
        lines.append("")
        lines.append("[build verification]  %d/%d components compiled"
                     % (n_ok, len(builds)))
        for comp, ok, detail in builds:
            lines.append("  [%s] %-44s %s"
                         % ("OK  " if ok else "FAIL", comp, detail))

    if deps:
        n_ok = sum(1 for d in deps if d["ok"])
        lines.append("")
        lines.append("[dependencies]  %d/%d present (report only, nothing installed)"
                     % (n_ok, len(deps)))
        for d in deps:
            mark = "OK  " if d["ok"] else "MISS"
            lines.append("  [%s] %-18s %s" % (mark, d["label"], d["detail"]))
            lines.append("         needed for: %s" % d["need"])
            if not d["ok"]:
                lines.append("         install:    %s" % d["hint"])

        cmds = install_commands(deps)
        if cmds:
            lines.append("")
            lines.append("  to install the missing dependencies, run:")
            for c in cmds:
                lines.append("    %s" % c)

    os.makedirs(DOCS_DIR, exist_ok=True)
    with open(LOG_FILE, "w") as f:
        f.write("\n".join(lines) + "\n")


