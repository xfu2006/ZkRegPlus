def main():
    # --verify-build: also compile the regexp -> R1CS pipeline and confirm it
    # builds (slow: first CirC build takes minutes). Default off (clone + patch
    # + dependency report only).
    do_build = "--verify-build" in sys.argv or "--build" in sys.argv

    # resolve all relative paths against the ms_dlp dir (never cwd / hardcoded).
    os.chdir(get_ms_dlp_dir())

    # wipe any prior clone so we always get a clean snapshot.
    if os.path.exists(DEST):
        print("[wipe] removing existing %s/" % DEST)
        shutil.rmtree(DEST)

    # full clone (no --depth); keep .git so the commit is pinned and re-fetchable.
    print("[clone] %s -> %s/" % (ZOMBIE_URL, DEST))
    rc, _out, err = run(["git", "clone", ZOMBIE_URL, DEST], timeout=CLONE_TIMEOUT)
    if rc != 0:
        # leave no partial tree behind on failure.
        if os.path.exists(DEST):
            shutil.rmtree(DEST)
        write_log("FAIL", "", 0, 0, err, None)
        print("[fail] %s" % err)
        print("[log]  %s" % LOG_FILE)
        raise SystemExit(1)

    # pin the commit.
    rc, commit, err = run(["git", "-C", DEST, "rev-parse", "HEAD"])
    if rc != 0:
        commit = ""

    write_upstream(commit)

    # apply standalone-build patches to the fresh clone.
    print("[patch] applying build patches to the clone...")
    patches = apply_patches()
    for p in patches:
        print("  %s" % p)

    nfiles, nbytes = tree_size(DEST)

    # report (do not install) the full-repo build dependencies.
    print("[deps] checking build dependencies (report only)...")
    deps = check_dependencies()
    for d in deps:
        print("  [%s] %-18s %s" % ("OK  " if d["ok"] else "MISS",
                                   d["label"], d["detail"]))

    # optionally verify the clone actually compiles.
    builds = None
    if do_build:
        print("[build] verifying compilation (this can take several minutes)...")
        builds = verify_build()
        for comp, ok, detail in builds:
            print("  [%s] %s -- %s" % ("OK  " if ok else "FAIL", comp, detail))
    else:
        print("[build] skipped (pass --verify-build to compile and verify)")

    write_log("OK", commit, nfiles, nbytes, "", deps, patches, builds)

    n_ok = sum(1 for d in deps if d["ok"])
    print("[ok]   commit %s" % (commit or "unknown"))
    print("[ok]   %d files, %.1f MiB" % (nfiles, nbytes / (1024.0 * 1024.0)))
    print("[deps] %d/%d present" % (n_ok, len(deps)))
    cmds = install_commands(deps)
    if cmds:
        print("[deps] to install the %d missing dependencies, run:" % (len(deps) - n_ok))
        for c in cmds:
            print("         %s" % c)
    if builds is not None:
        b_ok = sum(1 for (_c, ok, _d) in builds if ok)
        print("[build] %d/%d components compiled" % (b_ok, len(builds)))
    print("[log]  %s" % LOG_FILE)

    # final completeness check: when a build was requested, fail loudly (and
    # with a non-zero exit) unless every Zombie component compiled.
    if builds is not None:
        failed = [comp for (comp, ok, _d) in builds if not ok]
        if failed:
            print("[done] Zombie build INCOMPLETE -- did not compile: %s"
                  % ", ".join(failed))
            raise SystemExit(2)
        print("[done] Zombie build COMPLETE: all %d components compiled." % len(builds))


if __name__ == "__main__":
    main()
