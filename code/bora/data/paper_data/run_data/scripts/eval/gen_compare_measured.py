"""Generate the measured comparison table of Sec. 6.5 (W203, OD27).

ALL_T1020 (W807 b): replaces gen_compare_all.py (old Table 4, deleted).
Measured cells only, no projection and no speedup factor:
  Dna  -- Reef on its 60 sampled rules (dna_reef_bora.reef_total) vs BORA on
          all rules (dna_reef_bora.bora_main_folding_cost), both net.
  Dlp  -- Zombie vs BORA on the same random e-mails per arm (L_T): Zombie
          from the same-sample TSV (D5), BORA from same_dlp.tgz (D6).
An arm whose D5 or D6 log is missing is omitted (OD39 a).

Reads (ALL_T1020, W807 g): data/raw_data/jet1tb/reef_sample_run.log
(Reef, whatever the server), and under data/raw_data/<SERVER_TO_USE>/:
  full_dna.tgz, same_zombie_regex_zombie_international.tsv, same_dlp.tgz
Writes:
  <fig_dir>/compare_measured.tex
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE.parent))
sys.path.insert(0, str(_HERE))
from common import (server_file, reef_file, resolve_server_dump, _phase_total,
                    fig_dir, source_line, MISSING)
from dna_reef_bora import (parse_reef_log, reef_total, bora_main_folding_cost,
                           BUCKETS, fmt_human, _try)
from gen_zombie_table import same_sample, SAME_TSV, ARMS

_SEG = re.compile(r"SAME fold begin i=(\d+) size=(\d+) n=(\d+)\n(.*?)"
                  r"SAME fold end i=\1\b", re.S)


def bora_same(path) -> dict:
    """{arm: (emails, net seconds)}: Phase-1 net of each same_dlp segment
    [U: parser to be re-checked on the first real same_dlp log]."""
    text = Path(resolve_server_dump(path)).read_text(errors="replace")
    return {int(m.group(2)): (int(m.group(3)), _phase_total(m.group(4), 1))
            for m in _SEG.finditer(text)}


def build_table(reef, bora_dna, zomb, bsame) -> str:
    rows, note = [], ""
    if reef:
        n, t = reef_total(reef)
        rules = sum(reef[b]["count"] for b in BUCKETS)
        rows.append(rf"\textsc{{Dna}} & Reef, {n} sampled rules & "
                    rf"{fmt_human(t)} & ${t / n:.1f}$\,s$^a$ \\")
        note = rf"$^a$Mean over {n} sampled rules, unweighted."   # OD27
    else:
        rows.append(rf"\textsc{{Dna}} & Reef & {MISSING} & \\")
    if bora_dna is not None and reef:
        rows.append(rf" & BORA, all {rules:,} rules & {fmt_human(bora_dna)} "
                    rf"& ${bora_dna / rules:.2f}$\,s$^b$ \\")
        note += (rf" $^b$Amortized: net of one proof over all {rules:,} "
                 r"rules.")                     # ALL_T1020 Q4 (owner 11/19)
    else:
        rows.append(rf" & BORA & {MISSING} & \\")
    tot = []                                    # ALL_T1020 Q4: all-arms line
    for arm in ARMS:
        z, b = zomb.get(arm), bsame.get(arm)
        if z is None or b is None:
            rows.append(f"% OMITTED Dlp {arm} B (OD39 a): Zombie "
                        f"{z is not None}, BORA {b is not None}")
            continue
        nb, tb = b
        rows += [r"\midrule",
                 rf"\textsc{{Dlp}}, {arm:,}\,B & Zombie, {z['emails']} "
                 rf"e-mails & {fmt_human(z['prove_s'] * z['emails'])} & "
                 rf"${z['prove_s']:.1f}$\,s \\",
                 rf" & BORA, {nb} e-mails & {fmt_human(tb)} & "
                 rf"${tb / nb:.1f}$\,s \\"]
        tot.append((z["emails"], z["prove_s"] * z["emails"], nb, tb))
    if len(tot) == len(ARMS):                   # every arm measured (OD39 a)
        zn, zt, bn, bt = (sum(c) for c in zip(*tot))
        rows += [r"\midrule",
                 rf"\textsc{{Dlp}}, all arms & Zombie, {zn} e-mails & "
                 rf"{fmt_human(zt)} & ${zt / zn:.1f}$\,s \\",
                 rf" & BORA, {bn} e-mails & {fmt_human(bt)} & "
                 rf"${bt / bn:.1f}$\,s \\"]
    return "\n".join([
        r"% GENERATED by data/scripts/eval/gen_compare_measured.py -- do not edit.",
        source_line(reef_file(), *map(server_file, (
            "full_dna.tgz", SAME_TSV, "same_dlp.tgz"))),
        r"\begin{table}[t]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}l l r r@{}}",
        r"\toprule",
        r"Data & System, input & Net & Mean \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        # Caption defines Net/Mean and each system's net (owner 11/20).
        r"\caption{Measured prover cost. \emph{Net} is the total over the "
        r"listed inputs, and \emph{Mean} divides it by the number of rules"
        + (r" (\textsc{Dna}) or e-mails (\textsc{Dlp})"
           if any(r.startswith(r"\textsc{Dlp}") for r in rows) else "")
        + r". For Reef and BORA, net is "
        r"as in Table~\ref{tab:dna-reef-bora}. It excludes commitment, setup "
        r"and BORA's per-run compression. "
        + (r"For Zombie, net is the Spartan prove time summed over each "
           r"e-mail's accepted proofs, without key generation or verification. "
           r"In \textsc{Dlp}, both systems prove the same random Enron "
           r"e-mails, padded to each length. BORA's compression is left out "
           r"because the sample is too small to amortize the decider proof "
           r"cost. "
           if any(r.startswith(r"\textsc{Dlp}") for r in rows) else "")
        + note + "}",
        r"\label{tab:compare-measured}",
        r"\end{table}",
        "",
    ])


def main() -> None:
    reef = _try("Reef log", lambda: parse_reef_log(reef_file()))
    bora_dna = _try("BORA Dna dump", lambda: bora_main_folding_cost(
        resolve_server_dump("full_dna.tgz")))
    zomb = same_sample(server_file(SAME_TSV))
    bsame = _try("BORA same-sample (D6)", bora_same, "same_dlp.tgz") or {}
    out = fig_dir() / "compare_measured.tex"
    out.write_text(build_table(reef, bora_dna, zomb, bsame))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
