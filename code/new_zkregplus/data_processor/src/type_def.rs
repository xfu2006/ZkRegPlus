pub struct SubsigStepStore{
	/// sorted, generated by acdfa::gen_subsig_id (note: do start from 1)
	/// it is a concat of sig_id (start from 1) || subsig_id (start from 1)
	pub subsig_ids: Vec<usize>,
	/// map from subsig_id to the record. We assume that
	/// item is small, so returning by clone is ok.
	pub subsig_to_steps: HashMap<usize, SubsigStepStoreItem>,
}


/// Stores SubsigPatternStore, related Sigs, related pattern_map_to_sig
/// and related ACDFA.
/// Note "0" entry corresponds to all. and its ACDFA entry 0 is 
/// is the ACDFA bag-words (pm approach) for ALL sigs. Then after
/// entry #1, its for individual sigs. 
/// Note that the vec_sigs[0] is a vector of ALL sigs,
/// and then startging from i>=1, vec_sigs[i] is a SINGLE ELEMENT
/// vector containing one ClamavSig, whose pm_bound_vec is generated
/// using cfg (min_pm_word=0) for ISED.
#[derive(Serialize, Deserialize,Clone)]
pub struct BundleSubsigStore{
	/// whether it's for ignore case
	pub b_igc: bool,
	/// the first entry is "all". Then after 1st entry, is one individual
	/// signature name
	pub vec_sig_names: Vec<String>,
	/// the corresponding sig corresponding signame. For 0'th entry,
	/// its the collection of ALL signatures. It's >=1 entries are
	/// vector of single elements
	pub vec_sigs: Vec<Vec<Arc<ClamavSig>>>, 
	/// acdfa corresponds to vec_sigs one by one.
	pub vec_acdfa: Vec<HexACDFA>,

	// -- subsig - state - pat database
	/// encodes the subsig-state-pattern information 
	pub vec_subsig_stores: Vec<SubsigPatternStore>,
	/// map from pattern to signature names
	pub vec_map_pattern_sig: Vec<HashMap<String,Vec<String>>>,

	// -- subsig - steps (pat, allowed_range)
	pub vec_subsig_step_stores: Vec<SubsigStepStore>,

	// -- subsig - counter constraint related info
	pub vec_subsig_info_stores: Vec<SubsigInfoStore>
}


