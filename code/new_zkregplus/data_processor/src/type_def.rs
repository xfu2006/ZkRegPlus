/// Store the information subsig -> acdfa states -> pattens
/// where the patterns are restricted to those related to the subsig
#[derive(Serialize, Deserialize,Clone,Debug)]
pub struct SubsigPatternStore{
	/// sorted, generated by acdfa::gen_subsig_id (note: do start from 1)
	/// it is a concat of sig_id (start from 1) || subsig_id (start from 1)
	pub subsig_ids: Vec<usize>,
	/// map from subsig_id to the record. We assume that
	/// item is small, so returning by clone is ok.
	pub subsig_to_rec: HashMap<usize, SubsigPatternStoreItem>,
}

/// One record in SubsigInfoStore
/// It contains the information of the type of subsig, 
/// and also the information for counter constraints and subsit_counter
/// constraints (if regular, related items are dummy values)
#[derive(Serialize, Deserialize,Clone,Debug)]
pub struct SubsigInfoStoreItem{
	/// the subsig ID
	pub subsig_id: usize,
	/// the subsig type converted from SubSigType (0-GeneralRegex, ...)
	pub subsig_type: u8, //converted from SubSigType
	/// the operator CompOp (default 0 - no op)
	pub comp_op: u8, 
	/// the num related to comp_op (default 0, will yield tautology)
	pub comp_num: u32,
	/// the min_required (if SubsigConounterConstraint, default 0)
	pub min_required: usize,
	/// the related subsigs (if SubsigCounterConstraint). 
	/// Note its size range from 0 to 62. So we would have to end
	/// up with a flexible size data table design.
	/// There are 383 subsigs among 2k subsigs that has SubsigCountConstraint
	/// type. The avg number of component subsigs is about 3 (including all 
	/// 2k other general subsigs)
	pub component_subsigs: Vec<usize>,
}

