/// One record in SubsigStepStore
#[derive(Serialize, Deserialize,Clone,Debug)]
pub struct SubsigStepStoreItem{
	/// the subsig ID (which matches SubsigPatStoreItem's
	pub subsig_id: usize,
	/// whether the subsig is IGC
	/// NOTICE that this is a TRUE flag of the subsig.
	/// Even if the store is a NON-matching igc, this flag is set as it is
	/// if non-match igc, the vec_p_bounds will be set to empty.
	/// will eventually leads to FALSE for non-match igc mode (in sed),
	/// which is OK, because compute_sig_adv will pick the correct result
	/// based on IGC attribute.
	pub igc: bool,
	/// step info (this is basically retrieved from
	/// vec_subsig_pm_bounds of the Sig object
	/// NOTICE that if the b_ignore_case does not match with the store
	/// or the subsig is a composite of subsig  (TotalSubsigCount type)
	/// this vector is set to empty
	/// each element represents a step:
	/// (pat_id, (a, b))
	/// where pat_id starts from 0 (raw pattern id), 
	/// (a,b) are the ranges, a,b are included, e.g., (1,1) as a range 
	/// they represent the allowed distance of current pat from
	/// any valid word in the previous step. (read clamav.rs::
	///     approx_eval_pm_bounds_subsig).
	/// *** SPECIFIC NOTE ***: here (a,b) are the ORIGINAL vec_pm_bounds
	/// value in ClamavSig object PLUS the pattern word length (reason:
	///  the location of the acc_state is at the END of the word)
	pub vec_pm_bounds: Vec<(usize, (usize, usize))>
}


/// Store the information subsig -> steps (note that this is
/// specific to b_ignore_case. If not match then the corresponding
/// list of steps is empty because acdfa used does not match)
