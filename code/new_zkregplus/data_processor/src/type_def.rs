#[derive(Debug,Clone)]
/// It represents the raw parsing of clamav main.ldb sig string
/// See <https://docs.clamav.net/manual/Signatures/LogicalSignatures.html>
/// for specification.
/// The eval_dnf represents a Disjunctive Normal Form (DNF)
/// that describes the execution order. The reason we use
/// DNF is that when the the formula is negated, applying
/// Demorgan's law allows to achieve a NFA with much smaller size.
#[derive(Serialize,Deserialize)]
pub struct ClamavSig{
	/// name of the clamav sig
	pub name: String,
	/// brief description 
	pub desc: String,
	/// the logical expression on subsigs, e.g., `(2|3|4)`
	pub expr: String,
	/// the first line of the clamav sig
	pub line: String,
	/// subsignature raw regex expressions
	pub vec_subsigs: Vec<String>,
	/// constructed subisg objects
	pub vec_subsig_obj: Vec<SubSigObj>,
	/// whether the subsignature needs to be negated
	pub vec_bneg: Vec<bool>,
	/// information of pcre subsig (default empty for general regex subisg)
	pub vec_pcre_info: Vec<PcreInfo>,  
	/// if the subsig is ignore-case
	pub vec_bcase_sensitive: Vec<bool>,
	/// logical expression converted to DNF format
	pub eval_dnf: EvalDNF,
	/// type of clamav sig
	pub sigtype: ClamSigType,
//	#[serde(skip_serializing)]
	/// list of automaton (only needs to build for a FEW)
	pub vec_subsig_automaton: Vec<Arc<DFA<char>>>, //each to a subsig_obj (optional)

	///(optional) for each subisg, it has a HashSet of `Vec<String>` (called Bag of Words). We require that all Bag of Words should have one of its element appear at least once (for regular constraint). Semantics is similar for counter constraint. 
	pub vec_subsig_bagwords: Vec<HashSet<Vec<String>>>, 
	///(optioal) vector of pm_bounds (works for both pm and general if 
	/// they are approximated).
	pub vec_subsig_pm_bounds: Vec<Vec<(String, (usize, usize) )>>,
	/// will fail crit_pat coz no crit_pat can be extracted
	pub b_no_crit_pat: bool,
}

#[derive(Clone,Serialize,Deserialize)]
pub struct EvalDNF{
	/// vector of vectors that represents a DNF. e.g., [ [0,1], [2,3] ] 
	/// represents (0|1) & (2|3), i.e., a CONJUNCTION of DISJUNCTIONS!
	/// IN another word, to prove "discharge" - not satisfying
	/// we only need to EITHER prove: both 0 and 1 are not matched
	/// OR both 2 and 3 are NOT matched
	pub vec_disjunc: Vec<Vec<usize>>,
}

