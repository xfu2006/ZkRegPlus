/// information of Pcre regex in signatures (for reporting)
#[derive(Serialize,Deserialize, Clone,Debug)]
pub struct PcreInfo{
	/// if it is pcre
	pub b_pcre: bool,
	/// if it has backreference
	pub b_backref: bool,
	/// if it has zero length assertion
	pub b_zero_assert: bool,
	/// pattern starts at begin
	pub b_begin: bool,
	/// pattern must ends at the end
	pub b_end: bool,
	/// has zk-check of boundary PARTICULARLY in the current item
	pub b_boundary: bool,
	/// original_str the original string (ONLY used at TOP ROOT LEVEL)
	/// for general regex of clamav, this isthe original string
	/// WITHOUT Preprocessing (the reason) - handling repeittion
	/// directly has more effiicency (avoiding a lot of DFA concats)
	pub original_str: String,
}

/// Subsignature type
#[derive(Debug,PartialEq,Clone,Serialize,Deserialize)]
pub enum SubSigType{
	/// general regex for General
	GeneralRegex = 0,
	/// counter constraint (like 0=1, 1=0), require the subsignature
	/// involved needs to be ONE single pattern word
	CounterConstraint = 1,
	/// SubsigCountConstraint expecting the MINIMUM number of
	/// subsignatures that are met
	SubsigCountConstraint = 2,
}

/// Object for encapsulating subsignature of a ClamavSig
#[derive(Debug,Clone,Serialize,Deserialize)]
pub struct SubSigObj{
	/// the original subsig string extracted from ClamAV signature
	pub value: String,
	/// type of subsig (general regex, counter, total counter etc)
	pub subsig_type: SubSigType,
	/// converted subsig string to cater to syntax accepted by Rustomaton,
	/// or with decorator/modifier handled (e.g., ignore case, wide char etc)
	pub real_value: String, //used for CounterType
	/// whether to ignore case
	pub b_ignore_case: bool, //whether the subsignature is ignoring case
	// the folowing are for SubsigCountConstraint ONLY
	// for all other types, set to empty set and 0
	/// the set of subsignature IDs
	pub set_subsigs: HashSet<usize>, 
	/// minimum required number of SATISFIED subsigs (used for counter
	/// constraint such as `(2|3|4)>3,2` which means that out of
	/// subsigs 2,3,4, there are is at least 4 matches, that match
	/// at least 2 distinct subsignatures.
	/// See doc: https://docs.clamav.net/manual/Signatures/LogicalSignatures.html (4.7.1)
	/// ``=X,Y: If the SUB-EXPRESSION A refers to a single signature then this signature must be matched exactly X times; if it refers to a (logical) block of signatures then this block must generate X matches and at least Y different signatures must get matched. ''
	pub min_required: usize,
}

