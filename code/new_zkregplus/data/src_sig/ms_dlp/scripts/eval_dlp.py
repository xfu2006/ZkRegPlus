# Purpose: evaluate the baked MS-DLP policy regexes (regex_zombie/) as actual
#          detectors against an email corpus. For every file in a directory
#          (recursively), test all policies and classify the file:
#            - "pass"    : matches NO policy (clean email);
#            - "flagged" : matches >=1 policy (sensitive data detected).
#          Parallel per-file. Writes docs/eval_<dirbasename>.log with a summary
#          (total / pass / flagged + per-policy tally) and an itemized list of
#          every flagged file with the policy name(s) it matched.
#
# MATCH ENGINE: Google RE2 (the `re2` / google-re2 package), NOT stdlib `re`.
#   The baked policies are regular (no backreferences/lookarounds) -- they are
#   meant for a DFA. Under stdlib `re` the adjacent variable-length quantifiers
#   in a few policies (e.g. the connection-string SITs: [^...]{8,32}.{0,300}KWS)
#   trigger catastrophic backtracking (~10 s per 128 KB email, each). RE2 is a
#   DFA engine: it matches the SAME regular language in linear time with no
#   backtracking. This lets us run every regex_zombie/ file EXACTLY AS STORED --
#   nothing in regex_zombie/ is modified or rewritten.
#
# MATCH SEMANTICS (documented so the numbers are reproducible):
#   - each policy is the baked regex (PAT.{0,N}KWS)|(KWS.{0,N}PAT) from
#     regex_zombie/<slug>.regex, applied VERBATIM;
#   - case_sensitive = False : case-insensitive, matching real MS-DLP SIT
#     semantics (RE2's equivalent of re.IGNORECASE);
#   - dot_nl = True : '.' in the proximity window .{0,N} crosses newlines, so
#     PAT and KWS may sit on different email lines (RE2's equivalent of
#     re.DOTALL);
#   - max_mem raised so RE2 keeps the full DFA in memory (avoids the slower
#     fallback + "DFA out of memory" stderr noise on the larger policies);
#   - verified on the corpus: RE2 and stdlib `re` agree on match presence for
#     every policy that `re` can evaluate without hanging (0 disagreements).
#
# NOTE: there is no get_root_proj_dir() helper in src_sig; the project convention
#   (see measure.py) is to anchor the corpus path relative to __file__. We follow
#   that convention here. The parallel-scan scaffold (per-worker compile via the
#   pool initializer, gen_report_header, docs/ output) also mirrors measure.py.
#
# NOTE: code partly generated by Claude Code. Audited by author.
# -------------------------------------------

import os
import sys
from concurrent.futures import ProcessPoolExecutor

# common.py lives beside this script (scripts/); import provenance helpers.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import gen_report_header  # noqa: E402

# --- configuration ---------------------------------------------------------
FULL_DIR = "regex_zombie"               # input: baked policy regexes (READ-ONLY)
DOCS_DIR = "docs"
# email corpus, relative to this script (scripts/ -> ms_dlp -> src_sig -> data).
# same anchoring convention as measure.py (no get_root_proj_dir in the tree).
SAMPLES_DIR = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    os.pardir, os.pardir, os.pardir, "samples", "email_merged128k"))

N_WORKERS = os.cpu_count() or 8
CHUNKSIZE = 16                          # files per task dispatched to a worker
RE2_MAX_MEM = 256 << 20                 # DFA budget per pattern (256 MiB)


# --- dependency check ------------------------------------------------------
# external tool dependency: the Google RE2 binding (google-re2, imports as
# `re2`). We verify it up front (same spirit as eval_reef.verify_tool_existence
# / download_zombie's dependency table) so a missing dep fails fast with an
# install hint instead of dying inside every worker process.
DEPS = [
    ("google-re2", "re2",
     "pip install --user google-re2",
     "linear-time DFA matcher; runs the baked regex_zombie/ policies verbatim "
     "without the catastrophic backtracking stdlib `re` hits on them"),
]


def check_dependencies():
    missing = []
    for name, module, install_hint, why in DEPS:
        try:
            __import__(module)
        except ImportError:
            missing.append((name, module, install_hint, why))
    if missing:
        lines = ["[eval_dlp] missing required dependency:"]
        for name, module, install_hint, why in missing:
            lines.append("  - %s (import %s)" % (name, module))
            lines.append("      install: %s" % install_hint)
            lines.append("      needed:  %s" % why)
        raise SystemExit("\n".join(lines))


# --- policy loading --------------------------------------------------------
# read every regex_zombie/<slug>.regex into [(slug, pattern_str)]. Pattern
# strings (not compiled objects) are returned so they pickle cleanly to the
# worker processes, which compile them once via the pool initializer. The files
# are opened READ-ONLY; nothing under regex_zombie/ is ever written.
def load_policies(full_dir=FULL_DIR):
    policies = []
    for fn in sorted(os.listdir(full_dir)):
        if not fn.endswith(".regex"):
            continue
        with open(os.path.join(full_dir, fn), encoding="utf-8") as f:
            policies.append((fn[:-6], f.read().strip()))
    return policies


# --- per-file scan (runs in worker processes) ------------------------------
# the compiled patterns are large; compile them ONCE per worker via the pool
# initializer and stash them in a module global, rather than pickling per task.
_COMPILED = None


def _re2_options():
    # RE2 options equivalent to re.IGNORECASE | re.DOTALL, with a raised DFA
    # budget and stderr logging off (the larger policies otherwise emit a noisy
    # "DFA out of memory" line before falling back).
    import re2
    o = re2.Options()
    o.case_sensitive = False    # == re.IGNORECASE
    o.dot_nl = True             # == re.DOTALL ('.' matches newline)
    o.max_mem = RE2_MAX_MEM
    o.log_errors = False
    return o


def _init_worker(policies):
    global _COMPILED
    import re2
    opts = _re2_options()
    _COMPILED = [(name, re2.compile(pat, opts)) for name, pat in policies]


# scan one email file. Returns the sorted list of policy names that match
# (empty list = clean). Returns None if the file cannot be read.
def _check_file(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
    except OSError:
        return None
    # pad with whitespace: the policies flank each keyword with a CONSUMED
    # whitespace class (see gen_zombie_regex.sit_to_regex), so a keyword sitting
    # at the very first/last byte of the file would otherwise miss its boundary.
    text = " " + text + " "
    hits = [name for name, rx in _COMPILED if rx.search(text) is not None]
    return sorted(hits)


# --- directory evaluation --------------------------------------------------
# walk dirpath recursively, scan every file against all policies in parallel,
# and return (rel_results, n_files, n_unreadable) where rel_results maps each
# file's path (relative to dirpath) to its sorted list of matched policy names.
def eval_dir(dirpath, policies):
    files = []
    for root, _dirs, names in os.walk(dirpath):
        for n in sorted(names):
            p = os.path.join(root, n)
            if os.path.isfile(p):
                files.append(p)
    files.sort()
    print("[corpus] %d files under %s" % (len(files), dirpath))
    if not files:
        raise SystemExit("[corpus] no files found at %s" % dirpath)

    rel_results = {}
    n_unreadable = 0
    done = 0
    with ProcessPoolExecutor(max_workers=N_WORKERS,
                             initializer=_init_worker,
                             initargs=(policies,)) as ex:
        for path, hits in zip(files, ex.map(_check_file, files,
                                            chunksize=CHUNKSIZE)):
            done += 1
            rel = os.path.relpath(path, dirpath)
            if hits is None:
                n_unreadable += 1
            else:
                rel_results[rel] = hits
            if done % 1000 == 0 or done == len(files):
                print("[scan] %d/%d files" % (done, len(files)))
    return rel_results, len(files), n_unreadable


# --- log -------------------------------------------------------------------
# write docs/eval_<dirbasename>.log: provenance header, then a summary
# (total / pass / flagged + per-policy tally) and an itemized list of every
# flagged file with the policy name(s) it matched.
def write_log(dirbasename, dirpath, policies, rel_results, n_files,
              n_unreadable):
    flagged = {rel: hits for rel, hits in rel_results.items() if hits}
    n_scanned = len(rel_results)
    n_flagged = len(flagged)
    n_pass = n_scanned - n_flagged

    # per-policy tally: how many files each policy flagged (0 for silent ones).
    tally = {name: 0 for name, _ in policies}
    for hits in flagged.values():
        for name in hits:
            tally[name] += 1

    log_file = os.path.join(DOCS_DIR, "eval_%s.log" % dirbasename)
    os.makedirs(DOCS_DIR, exist_ok=True)
    with open(log_file, "w") as f:
        f.write(gen_report_header("MS-DLP policy match evaluation"))
        f.write("\n\n")
        f.write("policies:    %s/  (%d baked policy regexes, read verbatim)\n"
                % (FULL_DIR, len(policies)))
        f.write("corpus:      %s\n" % dirpath)
        f.write("engine:      Google RE2 (linear-time DFA)\n")
        f.write("match:       case_sensitive=False, dot_nl=True "
                "(== re.IGNORECASE | re.DOTALL)\n")
        f.write("definition:  pass = matches NO policy; "
                "flagged = matches >=1 policy\n")

        f.write("\n== SUMMARY ==\n")
        f.write("files scanned:   %d\n" % n_scanned)
        if n_unreadable:
            f.write("unreadable:      %d (excluded from totals)\n"
                    % n_unreadable)
        f.write("pass (clean):    %d\n" % n_pass)
        f.write("flagged:         %d\n" % n_flagged)

        f.write("\n== PER-POLICY TALLY (files flagged) ==\n")
        for name in sorted(tally, key=lambda k: (-tally[k], k)):
            f.write("  %-52s %d\n" % (name, tally[name]))

        f.write("\n== FLAGGED FILES (itemized) ==\n")
        if not flagged:
            f.write("  (none)\n")
        for rel in sorted(flagged):
            f.write("  %s: %s\n" % (rel, ", ".join(flagged[rel])))

    print("[eval_dlp] %s : %d scanned, %d pass, %d flagged"
          % (log_file, n_scanned, n_pass, n_flagged))
    return log_file


# -------------------------------------------
# MAIN
# -------------------------------------------
def main():
    check_dependencies()
    # anchor cwd to ms_dlp/ (parent of scripts/) so FULL_DIR / DOCS_DIR resolve
    # regardless of the invocation directory (same convention as measure.py).
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir))

    policies = load_policies()
    print("[policies] %d loaded from %s/" % (len(policies), FULL_DIR))
    if not policies:
        raise SystemExit("[policies] none found; run gen_zombie_regex.py first")

    rel_results, n_files, n_unreadable = eval_dir(SAMPLES_DIR, policies)
    write_log(os.path.basename(SAMPLES_DIR), SAMPLES_DIR, policies,
              rel_results, n_files, n_unreadable)


if __name__ == "__main__":
    main()
