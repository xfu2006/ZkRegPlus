def measure_combo(tag, ds_name, ds_dir, rs_dir, chunk_bytes):
    if not os.path.isdir(rs_dir):
        print("[measure_v2] ruleset %s/ absent -- skip %s" % (rs_dir, tag))
        return None
    clean_list = os.path.join(DOCS_DIR, "clean_email_list_%s.txt" % tag)
    report_file = os.path.join(DOCS_DIR, "measure_v2_report_%s.txt" % tag)

    sits = collect_sits(rs_dir)
    print("[sits] %s : %d SITs, N_sig max=%d from %s/"
          % (tag, len(sits), max((s[1] for s in sits), default=0), rs_dir))
    if not sits:
        print("[measure_v2] no SITs in %s/ -- run gen_zombie_regex.py"
              % rs_dir)
        return None

    # flatten SITs -> keyword vocab + maps for the workers.
    nsig = [s[1] for s in sits]
    names = [s[0] for s in sits]
    kw2sits = {}
    for sid, (_nm, _ns, kws) in enumerate(sits):
        for kw in kws:
            kw2sits.setdefault(kw, []).append(sid)
    kw2sits = {k: tuple(v) for k, v in kw2sits.items()}
    keywords = sorted(kw2sits)

    files = read_clean_list(clean_list, str(ds_dir))
    print("[corpus] %s : %d clean files" % (tag, len(files)))
    if not files:
        print("[measure_v2] no clean files -- run eval_dlp.py first")
        return None

    needs, distinct, topsits, kept, done = [], [], [], [], 0
    with ProcessPoolExecutor(max_workers=N_WORKERS,
                             initializer=_init_worker,
                             initargs=(keywords, kw2sits, nsig, names,
                                       chunk_bytes)) as ex:
        for path, res in zip(files, ex.map(_scan_file, files,
                                           chunksize=CHUNKSIZE)):
            done += 1
            if res is not None:
                nd, ds, tk = res
                needs.append(nd); distinct.append(ds); topsits.append(tk)
                kept.append(path)
            if done % 5000 == 0 or done == len(files):
                print("[scan] %s : %d/%d" % (tag, done, len(files)))

    write_report(report_file, rs_dir, ds_dir, clean_list, sits, needs,
                 distinct, topsits, kept, chunk_bytes)
    print("[report] %s -> %s" % (tag, report_file))
    return {"tag": tag, "files": len(kept),
            "needs_max": max(needs) if needs else 0,
            "needs_avg": (sum(needs) / len(needs)) if needs else 0}


def main():
    os.chdir(get_ms_dlp_dir())          # resolve relative paths
    chunk_bytes = CHUNK_BYTES
    if len(sys.argv) > 1:               # optional chunk-size override (bytes)
        chunk_bytes = int(sys.argv[1])

    summaries = []
    for ds_name, ds_dir in DATASETS:
        for rs_dir in RULESETS:
            tag = "%s_%s" % (ds_name, rs_dir)
            print("\n=== measure_v2 %s (chunk=%dB) ==="
                  % (tag, chunk_bytes))
            s = measure_combo(tag, ds_name, ds_dir, rs_dir, chunk_bytes)
            if s:
                summaries.append(s)

    print("\n=== measure_v2 matrix summary ===")
    for s in summaries:
        print("  %-48s files=%d needs avg/max=%.1f/%d"
              % (s["tag"], s["files"], s["needs_avg"], s["needs_max"]))


if __name__ == "__main__":
    main()
