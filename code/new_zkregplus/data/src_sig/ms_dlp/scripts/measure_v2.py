# Date: 06/13/2026
# Purpose: rank CLEAN (unflagged) Enron emails by the REAL per-chunk ZK
#          proving cost -- the aggressive-mode "needs" metric, i.e. a faithful
#          Python mirror of HexACDFA::get_max_needs (data_processor) -- so the
#          sample1/sample2/sample3 manifests pick the genuinely expensive files.
#
# WHY measure.py was wrong (and this replaces it):
#   measure.py ranked files by max_occ_per_chunk = the RAW number of keyword
#   occurrences in the densest 64KB window. That is the WRONG cost proxy:
#     (1) it counts the keyword side only, unweighted -- but in aggressive mode
#         each present SIT pulls its WHOLE fan-out family of SED subsigs into
#         the per-chunk universe. One present keyword costs N_sig (the SIT's
#         fan-out count, ~100), not 1.
#     (2) it counts raw repeats ("company" x132) -- but the cost set is by
#         DISTINCT SIT present, so a repeated word adds nothing.
#     (3) its 64KB window is 32x the real ~2KB folding step.
#   Net effect: measure.py's "10 worst" reached needs~600 while the true corpus
#   worst is needs~9880 (16x), in files measure.py ranked nowhere near the top.
#
# THE METRIC (faithful to get_max_needs / clamav.rs max_needs_subsigs):
#   For each ~2KB chunk: needs_chunk = SUM over the DISTINCT SITs whose keyword
#   appears in that chunk of N_sig, where N_sig = the SIT's SDE fan-out count
#   (product of the cardinalities of the digit/class positions select_slots
#   pins, under the fan-out budget). file_needs = MAX over the file's chunks.
#   Anchor identity: in both arms (PAT.{0,N}KWS and KWS.{0,N}PAT) the pm-bound
#   anchor lands on the keyword side, shared by all N_sig fan-out variants, so
#   mult[anchor] = N_sig -- a present keyword contributes the whole family.
#   (A SIT in a chunk is by construction crit-present, hence in the discharge
#   universe, so the universe gate is subsumed by per-chunk presence.)
#
# FAITHFULNESS CAVEATS (documented so the numbers are reproducible):
#   - a SIT contributes N_sig when ANY of its keywords appears in the chunk
#     (vs. the single specific pm-bound anchor keyword): right magnitude/cost
#     intuition, slight over-count.
#   - chunk_size_bytes (~2KB) mirrors chunk_len=64 words x 31 B/word; Rust
#     chunks the nibble path, negligible rank impact. CLI-tunable (argv[1]).
#   - keyword match semantics carried over from measure.py: case-insensitive,
#     non-alphanumeric-flanked, internal whitespace -> \s+, non-overlapping
#     longest-first.
#   - N_sig uses the case-sensitive fan-out cardinality (digits are caseless,
#     so igc is a no-op for these number SITs).
#   - a PAT the porter cannot size (parse failure / unknown class category)
#     floors to N_sig=1 and prints a [warn] naming the SIT.
#
# NOTE: code partly generated by Claude Code. Audited by author.
