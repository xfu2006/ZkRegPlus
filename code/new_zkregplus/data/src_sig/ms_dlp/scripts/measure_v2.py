# Aggressive-mode fan-out knobs (must mirror the Rust DB build for this set):
#  - FANOUT_CAP  = ClamavApproxConfig.sde_rep_fanout_cap base (run uses 100).
#  - FANOUT_BOOST/main_fanout.dat = per-SIT cap *= boost for sigs whose name
